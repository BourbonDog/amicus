#!/usr/bin/env node
'use strict';

/**
 * Capture the FULL published `tools/list` schema into the committed fixture
 * tests/fixtures/mcp-tools-list.published.json.
 *
 * WHY THIS EXISTS. The v4.15.0 release council (PR #296, round 2) found that the
 * zod 3 -> 4 bump changed the published MCP schema at the byte level -- zod 3's
 * `z.record(z.any())` carried no key schema and so could not emit
 * `propertyNames: {type: 'string'}` -- and that the release had asserted the
 * public surface was unchanged without ever diffing it. The SDK converts with a
 * different library per zod major (v3: zod-to-json-schema, v4: zod/v4-mini's
 * toJSONSchema), so a dependency bump can move the wire with no amicus code
 * change at all.
 *
 * Hand-written per-property pins could not catch that: they only assert the
 * shapes someone thought to list, and they say nothing about the ones they
 * omit. This fixture is the pre/post diff mechanism instead -- every tool, every
 * property, as an MCP client actually receives it.
 *
 * RE-BLESSING. When a change legitimately moves the published schema, run:
 *
 *   node scripts/capture-mcp-schema.js
 *
 * then READ the resulting git diff before committing it. A diff here is a change
 * to amicus's only machine-facing public interface; it is never noise to
 * rubber-stamp, even when it is semantically inert (as the propertyNames
 * addition was).
 *
 * DESCRIPTIONS ARE STRIPPED, at every level. They are not stable input: the
 * `model` parameter and the start/fanout/council_run/continue descriptions
 * interpolate the caller's configured ALIAS list, so the published prose
 * differs between a developer's machine and the credential-scrubbed integration
 * rail -- a fixture carrying it fails for the environment rather than for a
 * change. The prose has its own dedicated unit tests (dynamic alias keys, no
 * hardcoded model ids, no brand names); this file pins the validation surface,
 * which is the part a dependency bump can move silently.
 */

const { spawn } = require('child_process');
const path = require('path');
const fs = require('fs');

const BIN = path.join(__dirname, '..', 'bin', 'amicus.js');
const OUT = path.join(__dirname, '..', 'tests', 'fixtures', 'mcp-tools-list.published.json');

function capture() {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [BIN, 'mcp'], {
      stdio: ['pipe', 'pipe', 'pipe'],
      env: { ...process.env },
    });
    let buffer = '';
    const pending = new Map();
    let nextId = 1;
    const timer = setTimeout(() => { child.kill(); reject(new Error('timed out waiting for tools/list')); }, 60000);

    child.stdout.on('data', (chunk) => {
      buffer += chunk.toString();
      let i;
      while ((i = buffer.indexOf('\n')) !== -1) {
        const line = buffer.slice(0, i).trim();
        buffer = buffer.slice(i + 1);
        if (!line) { continue; }
        try {
          const msg = JSON.parse(line);
          if (msg.id !== undefined && pending.has(msg.id)) {
            const resolveOne = pending.get(msg.id);
            pending.delete(msg.id);
            resolveOne(msg);
          }
        } catch { /* startup noise on stdout is not a protocol message */ }
      }
    });
    child.on('error', (err) => { clearTimeout(timer); reject(err); });

    const request = (method, params) => new Promise((res) => {
      const id = nextId++;
      pending.set(id, res);
      child.stdin.write(`${JSON.stringify({ jsonrpc: '2.0', id, method, params })}\n`);
    });

    (async () => {
      await request('initialize', {
        protocolVersion: '2024-11-05',
        capabilities: {},
        clientInfo: { name: 'capture-mcp-schema', version: '1.0.0' },
      });
      child.stdin.write(`${JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized', params: {} })}\n`);
      const listed = await request('tools/list', {});
      clearTimeout(timer);
      child.kill();
      resolve(listed.result.tools);
    })().catch((err) => { clearTimeout(timer); child.kill(); reject(err); });
  });
}

/** Recursively drop every `description`; see the note above on why. */
function stripDescriptions(node) {
  if (Array.isArray(node)) { return node.map(stripDescriptions); }
  if (node && typeof node === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === 'description') { continue; }
      out[k] = stripDescriptions(v);
    }
    return out;
  }
  return node;
}

/** Tools sorted by name so the fixture never churns on registration order. */
function normalize(tools) {
  return [...tools]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((t) => ({ name: t.name, inputSchema: stripDescriptions(t.inputSchema), annotations: t.annotations }));
}

capture()
  .then((tools) => {
    const doc = { note: 'Generated by scripts/capture-mcp-schema.js — read the diff, never rubber-stamp it.', tools: normalize(tools) };
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, `${JSON.stringify(doc, null, 2)}\n`, 'utf8');
    process.stdout.write(`captured ${doc.tools.length} tools -> ${path.relative(path.join(__dirname, '..'), OUT)}\n`);
  })
  .catch((err) => {
    process.stderr.write(`capture failed: ${err.message}\n`);
    process.exitCode = 1;
  });
